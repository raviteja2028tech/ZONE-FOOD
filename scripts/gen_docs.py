"""Generate the ER diagram and data dictionary from the live PostgreSQL catalog.

    python scripts/gen_docs.py            write docs/ER_DIAGRAM.md and docs/DATA_DICTIONARY.md
    python scripts/gen_docs.py --check    exit 1 if the committed docs differ from the live schema

Because both files are produced from pg_catalog, the diagram cannot drift from the
implemented schema; `--check` (run by the test-suite) proves it.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import psycopg

sys.path.insert(0, str(Path(__file__).resolve().parent))
from db_config import ROOT, pg_dsn  # noqa: E402

DOCS = ROOT / "docs"
EXCLUDE = {"schema_migrations"}

# Presentation order: follows the food lifecycle rather than alphabetical order.
GROUPS = [
    ("Geography and establishments", ["zone", "establishment_category", "establishment", "commercial_profile",
                                      "institutional_profile", "residential_profile"]),
    ("Identity and audit", ["recipient_org", "app_user", "audit_log"]),
    ("Food catalogue and inflow", ["food_category", "emission_factor", "food_item", "supplier", "procurement",
                                   "procurement_line", "inventory_lot"]),
    ("Preparation and service", ["dish", "dish_ingredient", "service_session", "preparation_batch", "consumption_record"]),
    ("Waste", ["waste_reason", "disposal_route", "waste_event"]),
    ("Redistribution", ["surplus_listing", "redistribution_claim"]),
    ("Context", ["locality_event", "zone_event"]),
]


def mermaid_type(t: str) -> str:
    t = re.sub(r"\(.*?\)", "", t)  # drop (10,3) / (120)
    t = t.replace("character varying", "varchar").replace("character", "char").replace("timestamp with time zone", "timestamptz")
    t = t.replace("timestamp without time zone", "timestamp").replace("time without time zone", "time")
    t = t.replace("double precision", "float8")
    return re.sub(r"[^A-Za-z0-9_]", "_", t.strip()).strip("_") or "text"


def load_catalog(conn: psycopg.Connection):
    tables = {}
    rows = conn.execute("""
        SELECT c.relname, c.oid, c.relkind, coalesce(obj_description(c.oid, 'pg_class'), '')
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r','p') AND NOT c.relispartition
        ORDER BY c.relname""").fetchall()
    for name, oid, relkind, comment in rows:
        if name in EXCLUDE:
            continue
        cols = conn.execute("""
            SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
                   pg_get_expr(d.adbin, d.adrelid), coalesce(col_description(a.attrelid, a.attnum), ''),
                   a.attgenerated <> ''
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE a.attrelid = %s AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum""", (oid,)).fetchall()
        pk = {r[0] for r in conn.execute("""
            SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
            WHERE i.indrelid = %s AND i.indisprimary""", (oid,))}
        uniq = {r[0] for r in conn.execute("""
            SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
            WHERE i.indrelid = %s AND i.indisunique AND NOT i.indisprimary AND i.indnatts = 1""", (oid,))}
        fks = conn.execute("""
            SELECT a.attname, rc.relname, ra.attname, con.confdeltype
            FROM pg_constraint con JOIN pg_class rc ON rc.oid = con.confrelid
            JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = con.conkey[1]
            JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = con.confkey[1]
            WHERE con.conrelid = %s AND con.contype = 'f' ORDER BY a.attname""", (oid,)).fetchall()
        checks = conn.execute("""SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint
                                 WHERE conrelid = %s AND contype IN ('c','u') ORDER BY conname""", (oid,)).fetchall()
        idx = conn.execute("""SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' AND tablename = %s
                              ORDER BY indexname""", (name,)).fetchall()
        tables[name] = {"comment": comment, "cols": cols, "pk": pk, "uniq": uniq, "fks": fks, "checks": checks,
                        "idx": idx, "partitioned": relkind == "p"}
    partitions = conn.execute("""SELECT count(*) FROM pg_inherits WHERE inhparent = 'waste_event'::regclass""").fetchone()[0]
    return tables, partitions


def render_er(tables) -> str:
    out = ["# ER diagram", "",
           "_Generated by `python scripts/gen_docs.py` from the live PostgreSQL catalog — do not edit by hand._", "",
           "Renders on GitHub and in VS Code (Markdown Preview Mermaid support). Crow's-foot notation: `||` exactly one, "
           "`o|` zero or one, `o{` zero or many, `|{` one or many.", "",
           "```mermaid", "erDiagram"]
    for name in sorted(tables):
        t = tables[name]
        out.append(f"  {name} {{")
        fk_cols = {f[0] for f in t["fks"]}
        for col, typ, notnull, default, comment, generated in t["cols"]:
            keys = [k for k, cond in (("PK", col in t["pk"]), ("FK", col in fk_cols), ("UK", col in t["uniq"])) if cond]
            out.append(f"    {mermaid_type(typ)} {col}" + (f" {','.join(keys)}" if keys else ""))
        out.append("  }")
    for name in sorted(tables):
        t = tables[name]
        for col, parent, pcol, ondel in t["fks"]:
            nullable = not next(c[2] for c in t["cols"] if c[0] == col)
            is_pk = col in t["pk"] and len(t["pk"]) == 1
            unique = is_pk or col in t["uniq"]
            if unique:
                card = "||--o|" if not is_pk else "||--o|"
            else:
                card = "|o--o{" if nullable else "||--o{"
            label = f"{col}"
            out.append(f'  {parent} {card} {name} : "{label}"')
    out += ["```", "",
            "## Reading guide", "",
            "* `establishment` is the supertype; `commercial_profile`, `institutional_profile` and `residential_profile` "
            "are disjoint 1:1 subtypes whose primary key is also the foreign key.",
            "* `zone` references itself (`parent_zone_id`): sector > block > street, queried with a recursive CTE.",
            "* `waste_event` is the fact table. It is RANGE-partitioned by month on `occurred_on`; the monthly partitions are "
            "children of `waste_event` and are omitted from the diagram.",
            "* `dish_ingredient` and `zone_event` resolve many-to-many relationships.",
            "* MongoDB collections are not drawn here; see [DATA_MODEL.md](DATA_MODEL.md).", ""]
    return "\n".join(out)


def render_dictionary(tables, partitions) -> str:
    out = ["# Data dictionary", "",
           "_Generated by `python scripts/gen_docs.py` from the live PostgreSQL catalog — do not edit by hand. "
           "Descriptions come from `COMMENT ON` statements in migration 011._", "",
           f"`waste_event` has {partitions} child partitions (monthly, plus a DEFAULT partition). "
           "`schema_migrations` (migration bookkeeping) is omitted.", ""]
    for title, names in GROUPS:
        out += [f"## {title}", ""]
        for name in names:
            t = tables[name]
            out += [f"### `{name}`" + (" _(partitioned)_" if t["partitioned"] else ""), ""]
            if t["comment"]:
                out += [t["comment"], ""]
            out += ["| Column | Type | Null | Default | Key | Description |", "|---|---|---|---|---|---|"]
            fk = {f[0]: f"FK → {f[1]}.{f[2]}" for f in t["fks"]}
            for col, typ, notnull, default, comment, generated in t["cols"]:
                key = ", ".join(x for x in ("PK" if col in t["pk"] else "", fk.get(col, ""), "UNIQUE" if col in t["uniq"] else "") if x)
                dflt = ("generated" if generated else (default or "")).replace("|", "\\|")
                out.append(f"| {col} | `{typ}` | {'NO' if notnull else 'yes'} | {('`' + dflt + '`') if dflt else ''} | {key} | {comment.replace('|', chr(92) + '|')} |")
            if t["checks"]:
                out += ["", "Constraints: " + "; ".join(f"`{n}` {d}" for n, d in t["checks"]).replace("\n", " ")]
            out += ["", "Indexes: " + (", ".join(f"`{n}`" for n, _ in t["idx"]) or "none"), ""]
    return "\n".join(out)


def build(dsn_db: str | None = None) -> dict[str, str]:
    with psycopg.connect(pg_dsn(dsn_db)) as conn:
        tables, partitions = load_catalog(conn)
    return {"ER_DIAGRAM.md": render_er(tables), "DATA_DICTIONARY.md": render_dictionary(tables, partitions)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--db")
    args = ap.parse_args()
    generated = build(args.db)
    if args.check:
        stale = [n for n, text in generated.items() if not (DOCS / n).exists() or (DOCS / n).read_text(encoding="utf-8") != text]
        if stale:
            sys.exit(f"STALE: {stale} differ from the live schema. Run: python scripts/gen_docs.py")
        print("docs/ER_DIAGRAM.md and docs/DATA_DICTIONARY.md match the live schema.")
        return
    DOCS.mkdir(exist_ok=True)
    for name, text in generated.items():
        (DOCS / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote docs/{name}")


if __name__ == "__main__":
    main()
